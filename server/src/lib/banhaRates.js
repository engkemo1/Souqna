const norm = (v) => String(v || '').trim().toLocaleLowerCase('ar-EG')
  .replace(/[ً-ٰٟ]/g, '').replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
  .replace(/[,\-،_.]/g, ' ').replace(/\s+/g, ' ').trim();

/**
 * One-time import (guarded by an app_settings flag so later edits in the admin are never overwritten).
 * - existing rows for the same area are updated to the sheet price (distance pricing switched off),
 * - new areas are added for every governorate ('*'),
 * - the old generic "Banha / بنها" row is removed (the customer must name a neighbourhood),
 * - the per-extra-store fee is set to EXTRA_STORE_FEE.
 */
export function importPaperRates(db) {
  if (db.prepare("SELECT 1 FROM app_settings WHERE key='delivery_paper_rates_v1'").get()) return;
  db.exec('BEGIN');
  try {
    const rows = db.prepare('SELECT id, governorate, city FROM delivery_rates').all();
    const byNorm = new Map();
    for (const r of rows) { const k = norm(r.city); if (!byNorm.has(k)) byNorm.set(k, []); byNorm.get(k).push(r.id); }
    const upd = db.prepare('UPDATE delivery_rates SET fee=?, distance_km=NULL WHERE id=?');
    const ins = db.prepare("INSERT OR IGNORE INTO delivery_rates(governorate, city, fee, distance_km) VALUES('*', ?, ?, NULL)");
    for (const [city, fee] of PAPER_RATES) {
      const ids = byNorm.get(norm(city));
      if (ids?.length) for (const id of ids) upd.run(fee, id);
      else ins.run(city, fee);
    }
    db.prepare("DELETE FROM delivery_rates WHERE lower(governorate)='qalyubia' AND city IN ('Banha','بنها') AND distance_km IS NOT NULL").run();
    db.prepare("INSERT INTO app_settings(key,value) VALUES('delivery_extra_pickup_stop_fee',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value").run(String(EXTRA_STORE_FEE));
    db.prepare("INSERT INTO app_settings(key,value) VALUES('delivery_paper_rates_v1','1')").run();
    db.exec('COMMIT');
    console.log(`[delivery] imported ${PAPER_RATES.length} area prices from the price sheet`);
  } catch (e) {
    try { db.exec('ROLLBACK'); } catch { /* ignore */ }
    console.error(`[delivery] price sheet import failed: ${e.message}`);
  }
}


