/**
 * One-time: fill lat/lng on the delivery_rates rows that match a sheet area. Later edits in the admin are never overwritten.
 */
export function importPaperCoords(db) {
  if (db.prepare("SELECT 1 FROM app_settings WHERE key='delivery_paper_coords_v1'").get()) return;
  db.exec('BEGIN');
  try {
    const rows = db.prepare('SELECT id, city FROM delivery_rates WHERE lat IS NULL').all();
    const byNorm = new Map();
    for (const r of rows) { const k = norm(r.city); if (!byNorm.has(k)) byNorm.set(k, []); byNorm.get(k).push(r.id); }
    const upd = db.prepare('UPDATE delivery_rates SET lat=?, lng=? WHERE id=?');
    let n = 0;
    for (const [city, lat, lng] of PAPER_COORDS) for (const id of byNorm.get(norm(city)) || []) { upd.run(lat, lng, id); n += 1; }
    db.prepare("INSERT INTO app_settings(key,value) VALUES('delivery_paper_coords_v1','1')").run();
    db.exec('COMMIT');
    console.log(`[delivery] set map locations on ${n} areas`);
  } catch (e) {
    try { db.exec('ROLLBACK'); } catch { /* ignore */ }
    console.error(`[delivery] map locations import failed: ${e.message}`);
  }
}
