/** Look of the day / outfit worn photos. Vertical/portrait format (e.g. 4:5 or full body), never cropped to landscape! */
export async function saveLookOfDayImage(buffer) {
  let webp;
  try {
    const meta = await sharp(buffer, { failOn: 'error' }).metadata();
    if (Math.min(meta.width || 0, meta.height || 0) < 200) throw badRequest('image_too_small', 'Image is too small (min 200px).');
    // Rotate EXIF and resize within max 1600x2000, preserving full aspect ratio (NO forced cropping):
    webp = await sharp(buffer)
      .rotate()
      .resize(1600, 2000, { fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 85 })
      .toBuffer();
  } catch (e) {
    if (e.code === 'image_too_small') throw e;
    throw badRequest('invalid_image', 'This file is not a supported image.');
  }
  const name = `look-of-day/${crypto.randomBytes(12).toString('hex')}.webp`;
  if (r2Enabled) { await r2Put(name, webp); return `${config.r2.publicUrl}/${name}`; }
  const file = path.join(config.mediaDir, name);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, webp);
  return `${config.mediaBaseUrl}/${name}`;
}

/** Best-effort removal of a previously saved department, stylist, look-of-day or ad photo. */
export async function removeDeptImage(url) {
  if (!url) return;
  try {
    // Only remove files that match names generated by this module. In particular,
    // never let an admin-supplied URL turn into a path traversal on the media volume.
    const m = String(url).match(/(?:^|\/)(departments\/[a-z0-9-]+-[a-f0-9]{8}\.webp|stylist\/avatar-[a-f0-9]{8}\.webp|homepage-ads\/[a-f0-9]{24}\.webp|look-of-day\/[a-f0-9]{24}\.webp)(?:[?#]|$)/i);
    if (!m) return;
    const name = m[1];
    if (url.startsWith(config.r2.publicUrl) && r2Enabled) await r2Delete(name);
    else await fs.rm(path.join(config.mediaDir, name), { force: true });
  } catch { /* ignore */ }
}
