/**
 * حارس ادعاءات رد الموديل (Gemini/Groq/…): بيفرّق بين
 *  - معلومة بيدّعي إنها حقيقة عن المنتج أو الطلب (خصم، خامة، مميزات، ميعاد توصيل، فرع، قطعة «لقيتهالك») → لازم تكون في البيانات
 *  - نصيحة تنسيق أو اقتراح («يمشي معاه بنطلون أبيض»، «جربي معاه شنطة جملي») → مسموحة حتى لو القطعة مش معروضة
 * بيرجع أسباب الرفض؛ قايمة فاضية = الرد مقبول من ناحية الحقائق دي.
 */
import { norm } from './text.js';

// جملة اقتراح/تنسيق: فعل تنسيق ومن غير أي كلمة توافر («لقيتلك / عندنا / متاح / هتلاقيه / تحت»)
const SUGGEST = /(^| )(?:و|ف)?(يمشي|تمشي|بيمشي|بتمشي|يليق|تليق|بيليق|بتليق|نسق|نسقي|نسقها|نسقه|تنسق|تنسقها|تنسقه|تنسقيه|تنسقيها|تلبس|تلبسي|البس|البسي|ممكن تضيف|ممكن تضيفي|ضيف|ضيفي|حط|حطي|جرب|جربي|جربه|هيبقي حلو مع|هتبقي حلوه مع|يتلبس|بيتلبس)( |$)/;
const AVAIL = /(^| )(?:و|ف)?(لقيتلك|لقيت|لاقيتلك|عندنا|موجود|موجوده|متاح|متاحه|متوفر|متوفره|هتلاقي|هتلاقيه|هتلاقيها|تحت|اخترتلك|جبتلك|جهزتلك|ضفتلك|اختارتلك)( |$)/;

/** يقسّم الرد لجمل ويرجّع بس الجمل اللي بتقرر حقائق (بيشيل جمل الاقتراح اللي مفيهاش ادعاء توافر). */
export function factualText(reply) {
  const parts = String(reply || '').split(/[.،!؟?\n؛;]+/).map((s) => s.trim()).filter(Boolean);
  const keep = parts.filter((p) => { const n = ` ${norm(p)} `; return !(SUGGEST.test(n) && !AVAIL.test(n)); });
  // «بـ900 بدل 1200»: «بدل» قبل رقم = «بدلًا من»، مش بدلة
  return keep.join('. ').replace(/بدل\s*(?:ال)?\s*[0-9٠-٩]/g, ' ');
}

const MATERIALS = ['قطن', 'كتان', 'صوف', 'جلد', 'شيفون', 'ستان', 'ساتان', 'حرير', 'بوليستر', 'فيسكوز', 'ليكرا', 'تريكو', 'قطيفه', 'شمواه', 'كريب', 'مودال', 'دنيم', 'فرو'];
const FEATURES = [
  { re: /(ووتر ?بروف|ضد الماء|ضد الميه|مقاوم للماء|مقاوم للميه)/, need: /(ووتر ?بروف|ضد الماء|ضد الميه|مقاوم)/ },
  { re: /(مبطن|مبطنه|بطانه)/, need: /(مبطن|بطانه)/ },
  { re: /(مبيكش|ميكش|لا يكش|مش بيكش|ضد الانكماش)/, need: /(يكش|انكماش)/ },
  { re: /(مبيبهتش|ميبهتش|لا يبهت|ثابت اللون|مش بيبهت)/, need: /(يبهت|ثابت اللون)/ },
  { re: /(بيمط|بتمط|استرتش|مطاط)/, need: /(مط|استرتش|ليكرا|مطاط)/ },
  { re: /(100 ?%|١٠٠ ?%|100 في الميه|مية في المية|ميه في الميه)/, need: /(100|١٠٠)/ },
];

/**
 * @param {string} reply
 * @param {{ picked: object[], parsed?: object }} ctx  picked = المنتجات المعروضة فعلًا في الرد
 * @returns {string[]}
 */
export function unsupportedClaims(reply, { picked = [] } = {}) {
  const out = [];
  const fact = ` ${norm(factualText(reply))} `;
  const data = ` ${norm(picked.map((p) => [p.name_ar, p.description_ar, p.material_ar, p.cat_text, p.care_ar].filter(Boolean).join(' ')).join(' . '))} `;

  // ---- خصم / عرض: مسموح بس لو منتج معروض سعره قبل الخصم أعلى، والنسبة لو اتقالت لازم تطابق (±2)
  // «مفيش خصم عليه» صادقة لو مفيش خصم فعلًا: النفي مش ادعاء
  const noDiscount = /(مفيش|مافيش|ما فيش|مش عليه|مش عليها|من غير|بدون) (خصم|خصومات|عرض|عروض|تخفيض)/.test(fact);
  const discountSaid = !noDiscount && /(^| )(خصم|خصومات|تخفيض|تخفيضات|اوكازيون|سيل|sale|ببلاش|مجانا|هديه مع)( |$)|(في|عليه|عليها|فيه) عرض|(^| )عروض( |$)|اشتري .{0,20} وخد/.test(fact);
  if (discountSaid) {
    const disc = picked.filter((p) => Number(p.compare_at_price) > Number(p.price) && Number(p.price) > 0);
    if (!disc.length || /(ببلاش|مجانا|هديه مع|اشتري .{0,20} وخد)/.test(fact)) out.push('claims_discount');
    else {
      const m = String(factualText(reply)).replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d))).match(/(\d{1,2}) ?(?:%|٪|في الميه|في المية)/); // النسبة من النص الخام: norm بيشيل «%»
      if (m) { const said = Number(m[1]); if (!disc.some((p) => Math.abs(Math.round((1 - p.price / p.compare_at_price) * 100) - said) <= 2)) out.push('claims_discount'); }
    }
  }
  // ---- ميعاد توصيل / توصيل مجاني: مش من حق الموديل يوعد. المسموح بس حقيقة المنصة «جوه بنها خلال يوم»
  const deliverySaid = /(هيوصلك|هتوصلك|هيوصل|هتوصل|يوصلك|هيكون عندك|هتكون عندك|هتستلم|هتستلمي|هتستلمه|هتستلميه|توصيل مجاني|التوصيل مجاني|توصيله مجاني|شحن مجاني|الشحن مجاني|شحنه مجاني|ببلاش توصيل|التوصيل ببلاش|خلال ساع|في نفس اليوم|توصيل نفس اليوم)/.test(fact);
  if (deliverySaid) {
    const platformFact = /بنها/.test(fact) && /خلال يوم/.test(fact) && !/(مجاني|ساع|النهارده|بكره)/.test(fact);
    if (!platformFact) out.push('claims_delivery');
  }
  // ---- فروع: المنصة محلات، مفيش «فروع» في البيانات
  if (/(^| )(فرع|فرعنا|فروع|فروعنا|الفرع|الفروع|بفرع|بفروع|فرعها|فروعها)( |$)/.test(fact)) out.push('claims_branch');
  // ---- خامة / مميزات بيقول إنها في المنتج: لازم تكون مكتوبة عند المحل
  const matSaid = MATERIALS.filter((m) => new RegExp(`(^| )(ال|بال|و|وال)?${m}( |$)`).test(fact));
  if (matSaid.some((m) => !new RegExp(`(^| )(ال|بال|و|وال)?${m}`).test(data))) out.push('claims_fabric');
  if (FEATURES.some((f) => f.re.test(fact) && !f.need.test(data))) out.push('claims_feature');
  return [...new Set(out)];
}
