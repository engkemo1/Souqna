async function runConversation(turns) {
  let session = null;
  let lastRes = null;
  for (const turn of turns) {
    if (typeof turn === 'string') {
      lastRes = await runModa([{ role: 'user', content: turn }], { products: CATALOG, now: NOW, session });
    } else {
      lastRes = await runModa([{ role: 'user', content: turn.text || '' }], { products: CATALOG, now: NOW, session, answers: turn.answers || undefined });
    }
    session = lastRes.session;
  }
  return lastRes;
}

function getPickedItems(res) {
  const tabs = res?.blocks?.tabs || [];
  return tabs.flatMap((t) => t.items || []);
}

function getPickedIds(res) {
  return getPickedItems(res).map((i) => i.id);
}

function getPickedKeys(res) {
  return getPickedItems(res).map((i) => i.key);
}

